#!/usr/bin/env python3
"""
HawaOS Boot Logo Generator (tools/gen_logo.py)

DESIGN.md Section 12. The logo is a one-colour mark (assets/logo.svg), so the
boot lockup is stored as coverage only and coloured at boot from the saved
theme: three 4-bit alpha layers that Display.cpp blends over the theme's `bg`:

- accent: the mark and the "OS" of the wordmark (the accent colour)
- text:   "Hawa" (the theme's text colour)
- dim:    the tagline "Breezy Elegance, Materialised" (textDim)

One set of layers serves every accent in light and dark: 3 x 220x88 / 2 bytes,
about 29 KB.
"""

import shutil
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

LOGO_W = 220
LOGO_H = 88
ICON_SIZE = 52
SUBLINE_TEXT = "Breezy Elegance, Materialised"


def load_mark(repo_root: Path, size: int) -> Image.Image:
    """The mark's coverage (L) at `size` px: from the SVG when ImageMagick is
    available (exact edges), else downscaled from the PNG."""
    svg = repo_root / "assets" / "logo.svg"
    png = repo_root / "assets" / "logo.png"
    magick = shutil.which("magick")
    if svg.exists() and magick:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "mark.png"
            # Rasterised large, then reduced, for even anti-aliasing.
            subprocess.run(
                [magick, "-background", "none", "-density", "384", str(svg),
                 "-resize", f"{size}x{size}", str(out)],
                check=True,
            )
            return Image.open(out).convert("RGBA").getchannel("A").copy()
    img = Image.open(png).convert("RGBA")
    return img.resize((size, size), Image.Resampling.LANCZOS).getchannel("A")


def render_layers(repo_root: Path):
    accent = Image.new("L", (LOGO_W, LOGO_H), 0)
    text = Image.new("L", (LOGO_W, LOGO_H), 0)
    dim = Image.new("L", (LOGO_W, LOGO_H), 0)

    fonts = repo_root / "assets" / "fonts"
    title_font = ImageFont.truetype(str(fonts / "Inter-Display-SemiBold.ttf"), 28)
    sub_font = ImageFont.truetype(str(fonts / "Inter-Regular.ttf"), 12)

    # Lockup: mark, then "Hawa" + "OS", centred together.
    measure = ImageDraw.Draw(text)
    w_hawa = measure.textlength("Hawa", font=title_font)
    w_os = measure.textlength("OS", font=title_font)
    gap = 12
    start_x = (LOGO_W - int(round(ICON_SIZE + gap + w_hawa + w_os))) // 2
    icon_y = 4
    accent.paste(load_mark(repo_root, ICON_SIZE), (start_x, icon_y))

    text_x = start_x + ICON_SIZE + gap
    text_y = icon_y + 10
    ImageDraw.Draw(text).text((text_x, text_y), "Hawa", font=title_font, fill=255)
    ImageDraw.Draw(accent).text(
        (int(round(text_x + w_hawa + 1)), text_y), "OS", font=title_font, fill=255
    )

    w_sub = measure.textlength(SUBLINE_TEXT, font=sub_font)
    ImageDraw.Draw(dim).text(
        (int(round((LOGO_W - w_sub) / 2.0)), 66), SUBLINE_TEXT, font=sub_font, fill=255
    )
    return accent, text, dim


def pack_a4(layer: Image.Image):
    """4 bits a pixel, first pixel in the high nibble, rows unpadded."""
    px = list(layer.getdata())
    out = []
    for i in range(0, len(px), 2):
        hi = (px[i] + 8) // 17
        lo = (px[i + 1] + 8) // 17 if i + 1 < len(px) else 0
        out.append((hi << 4) | lo)
    return out


def array_lines(name: str, values, per_line: int = 16):
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in values[i : i + per_line]) + ",")
    lines.extend(["};", ""])
    return lines


def generate_logo_header(repo_root: Path):
    out_path = repo_root / "include" / "boot_logo.h"
    accent, text, dim = render_layers(repo_root)

    lines = [
        "// =============================================================================",
        "// AUTO-GENERATED BY tools/gen_logo.py — DO NOT EDIT MANUALLY",
        "// Boot lockup as three 4-bit alpha layers, coloured from the theme at boot",
        "// (DESIGN.md Section 12)",
        "// =============================================================================",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
        "",
        "namespace BootLogo {",
        "",
        f"constexpr uint16_t WIDTH  = {LOGO_W};",
        f"constexpr uint16_t HEIGHT = {LOGO_H};",
        "",
        "// The mark and \"OS\": the accent.",
    ]
    lines += array_lines("kAccentA4", pack_a4(accent))
    lines.append("// \"Hawa\": the theme's text colour.")
    lines += array_lines("kTextA4", pack_a4(text))
    lines.append("// The tagline: textDim.")
    lines += array_lines("kDimA4", pack_a4(dim))
    lines.extend(["} // namespace BootLogo", ""])

    text_out = "\n".join(lines)
    # Rewritten only when it changes, so builds don't recompile Display.cpp.
    if not out_path.exists() or out_path.read_text() != text_out:
        out_path.write_text(text_out)
        print(f"[gen_logo] Generated {out_path.relative_to(repo_root)} "
              f"({LOGO_W}x{LOGO_H}, three A4 layers)")


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    generate_logo_header(root)
else:
    try:
        Import("env")  # type: ignore
    except NameError:
        pass
    else:
        generate_logo_header(Path(env.subst("$PROJECT_DIR")))  # type: ignore
